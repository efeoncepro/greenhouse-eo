import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { axisTypography, efeonceGraphicLine, efeonceTokens } from '@efeoncepro/axis-tokens'

const dir = resolve('scripts/public-website/blog-growth-form')
const growth = efeonceGraphicLine.lines.find(line => line.key === 'growth')!

// AXIS Growth filled actions use the vivid canonical teal on paper, with dark ink.
// Consumer adapter only: no package bump, copied hex values or global renderer recoloring.
const roles = {
  action: growth.accentOnDark,
  'action-ink': efeonceGraphicLine.color.dark,
  ink: efeonceGraphicLine.color.navy,
  paper: efeonceGraphicLine.color.paper,
  field: efeonceTokens.color.surface,
  boundary: growth.accentOnLight,
  radius: efeonceTokens.radius.lg,
  space: efeonceTokens.spacing[6],
  'small-space': efeonceTokens.spacing[4],
  'large-space': efeonceTokens.spacing[8],
  'title-size': axisTypography.scale.surfaceHeroTitle.size,
  'title-mobile-size': axisTypography.scale.surfaceHeroTitle.mobileSize,
  'title-weight': axisTypography.scale.surfaceHeroTitle.weight,
  'title-leading': axisTypography.scale.surfaceHeroTitle.lineHeight
}

const selectors = '.eo-blog-subscription, .elementor-18456 .elementor-element-2ee4ef0:has(.eo-blog-subscription)'

const generated = `/* Generated by build-host-styles.ts from installed AXIS tokens. Edit host-layout.css. */\n${selectors} {\n${Object.entries(
  roles
)
  .map(([key, value]) => `  --eo-blog-${key}: ${value};`)
  .join('\n')}\n}\n\n${readFileSync(resolve(dir, 'host-layout.css'), 'utf8')}`

if (process.argv.includes('--check')) {
  if (readFileSync(resolve(dir, 'host.css'), 'utf8') !== generated) throw new Error('Blog host styles are stale')
} else writeFileSync(resolve(dir, 'host.css'), generated)
