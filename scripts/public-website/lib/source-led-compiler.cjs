/**
 * Shared core of the source-led landing compilers (Agencia de Medios, Performance Marketing; reusable by any new
 * landing built from an approved Claude Design canvas).
 *
 * Contract: each landing script owns stage 1 only — it expands its canvas (static sc-if handling, DCLogic evaluation,
 * tabs, quiz, form host card…) into a cheerio document whose top-level <section> elements carry
 * data-gh-module="<module>" in the same order as `modules`, and collects the CSS it generated for expanded selectors
 * (`tabCss`). This core then compiles every section into one schema + template under
 * includes/<landing>/{schemas,templates}, writes assets/css/<landing>-landing.css (canvas CSS scoped to .gh-<landing>,
 * expanded selectors, host.css and the optional unscoped page.css) and refreshes <landing>-source/used-assets.json.
 * It never touches WordPress. The output must stay byte-identical for an unchanged source: verify with
 * scripts/public-website/verify-source-led-compilers.cjs before deploying.
 */
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const cheerio = require('cheerio')
const postcss = require('postcss')

const TEXT_KINDS = { p: 'Descripción', a: 'Botón', button: 'Botón', summary: 'Pregunta', figcaption: 'Pie', blockquote: 'Testimonio', li: 'Ítem', strong: 'Destacado', b: 'Destacado', span: 'Texto', dt: 'Etiqueta', dd: 'Descripción' }

const FORM_FIELDS = [
  { key: 'form_key', type: 'text', label: 'Formulario · form key publicado' },
  { key: 'form_surface', type: 'text', label: 'Formulario · surface' },
  { key: 'form_fallback', type: 'textarea', label: 'Formulario · texto sin JavaScript' },
]

const SERVICE_FIELDS = [
  { key: 'schema_service_name', type: 'text', label: 'Datos estructurados · nombre del servicio' },
  { key: 'schema_service_type', type: 'text', label: 'Datos estructurados · tipo de servicio' },
  { key: 'schema_service_description', type: 'textarea', label: 'Datos estructurados · descripción del servicio' },
  { key: 'schema_audience', type: 'text', label: 'Datos estructurados · audiencia' },
  { key: 'schema_area_served', type: 'text', label: 'Datos estructurados · países (separados por coma)' },
  { key: 'schema_service_catalog', type: 'textarea', label: 'Datos estructurados · componentes del servicio (uno por línea)' },
]

// Ohio's .links-underline paints `linear-gradient(currentcolor…)` on every link hover with higher specificity than the
// landing (5 classes). Buttons that set their fill with the `background` shorthand reset background-size, so the
// gradient covers the whole button and hides its text (Performance and Medios hero CTAs, 2026-10-17). Scoped to the
// landing by the selector rewrite below; no landing link uses its own background image.
const OHIO_LINK_GUARD = '/* Ohio link-underline guard */\na:hover,a:focus-visible{animation:none !important;background-image:none !important}\n'

const FORM_FALLBACK = 'Este formulario necesita JavaScript. Puedes escribirnos a hola@efeoncepro.com o agendar en efeoncepro.com/agenda.'

/**
 * @param {object} o
 * @param {string} o.landing        slug used for paths, CSS scope, schema id and asset prefix (e.g. 'medios')
 * @param {string} o.sourceDir      <landing>-source directory (host.css, optional page.css, used-assets.json)
 * @param {string} o.source         raw canvas HTML (its first <style> is the canvas stylesheet)
 * @param {object} o.assets         blob id → file name map (assets.json)
 * @param {Function} o.$            cheerio document from stage 1 with data-gh-module sections
 * @param {Array} o.modules         [module, editor title, Ohio scheme] in document order
 * @param {string[]} o.tabCss       CSS generated by stage 1 for expanded selectors
 * @param {string} o.formModule     module that hosts the Growth Form fields
 * @param {string} o.serviceModule  module that emits Service + FAQPage JSON-LD
 * @param {object} o.faq            { repeaters, question, answer } field keys for FAQPage
 * @param {object} o.serviceDefaults schema_* defaults
 * @param {object} [o.repeatLabels] repeater key → editor label
 * @param {boolean} [o.pageLayer]   append <sourceDir>/page.css unscoped
 * @param {string} [o.compilerFile] generator file name written in the CSS header
 */
function compileSourceLedLanding(o) {
  const runtime = process.env.PUBLIC_SITE_RUNTIME_ROOT || '/Users/jreye/Documents/efeonce-public-site-runtime'
  const plugin = path.join(runtime, 'wp-content/plugins/eo-elementor-widgets')
  const { landing, sourceDir, source, assets, $, modules, tabCss } = o
  const scope = '.gh-' + landing
  const envPrefix = landing.toUpperCase().replace(/[^A-Z0-9]+/g, '_')
  const sourceSha256 = crypto.createHash('sha256').update(source).digest('hex')

  const slug = value => value.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 24)
  const token = key => '%%' + key + '%%'
  const excerpt = value => value.replace(/\s+/g, ' ').trim().slice(0, 48)

  const textLabel = (q, node, value) => {
    const tag = node.parent.tagName
    const heading = q(node.parent).closest('h1,h2,h3,h4').get(0)

    const kind = heading
      ? { h1: 'Título principal', h2: 'Título', h3: 'Subtítulo', h4: 'Subtítulo' }[heading.tagName]
      : (TEXT_KINDS[tag] || 'Texto')

    return kind + ' · ' + excerpt(value)
  }

  const assetRef = src => {
    const m = /^\/_blob\/([0-9a-z-]+)$/.exec(src || '')

    if (!m) return src
    if (!assets[m[1]]) throw new Error('Unmapped asset ' + src)

    return '@' + landing + '/' + assets[m[1]]
  }

  // Inline style values can carry background images; map their blobs too (not editable, versioned with the plugin).
  const styleAssets = html => html.replace(/url\((['"]?)\/_blob\/([0-9a-f]{32})\1\)/g, (_, quote, id) => {
    if (!assets[id]) throw new Error('Unmapped style asset ' + id)

    return `url(${quote}%%asset_base%%${assets[id]}${quote})`
  })
    // SVG <image> nodes (isotypes inside diagrams) are part of the drawing, not editable media.
    .replace(/(<image\b[^>]*?\shref=")\/_blob\/([0-9a-f]{32})"/g, (_, head, id) => {
      if (!assets[id]) throw new Error('Unmapped SVG image ' + id)

      return head + '%%asset_base%%' + assets[id] + '"'
    })

  function compileFragment(html, module) {
    const q = cheerio.load(html, { decodeEntities: false }, false)
    const fields = []
    const defaults = {}
    let serial = 0

    const field = (type, label, value, extra = {}) => {
      const key = 'f' + String(++serial).padStart(3, '0') + '_' + slug(label.split(' · ')[0])

      fields.push({ key, type, label, ...extra })
      defaults[key] = value

      return token(key)
    }

    q('*').each((_, el) => {
      const node = q(el)

      for (const attr of Object.keys(el.attribs || {})) if (/^on/i.test(attr)) node.removeAttr(attr)

      if (el.tagName === 'gh-growth-form') {
        node.replaceWith(token('growth_form'))

        return
      }

      if (el.tagName === 'img') {
        node.attr('src', field('media', 'Imagen · ' + (node.attr('alt') || module), { url: assetRef(node.attr('src')), id: 0 }))
        if (node.attr('alt')) node.attr('alt', field('text', 'Texto alternativo · ' + excerpt(node.attr('alt')), node.attr('alt')))
        if (!node.attr('loading') && module !== 'hero') node.attr('loading', 'lazy')
        node.attr('decoding', 'async')
      }

      if (el.tagName === 'video') {
        const label = node.attr('aria-label') || 'Video'

        node.attr('src', field('video', 'Video · ' + excerpt(label), { url: assetRef(node.attr('src')), id: 0 }))
        if (node.attr('poster')) node.attr('poster', field('media', 'Póster del video · ' + excerpt(label), { url: assetRef(node.attr('poster')), id: 0 }))
        if (node.attr('aria-label')) node.attr('aria-label', field('text', 'Nombre accesible del video', node.attr('aria-label')))
      }

      if (el.tagName === 'source' && node.attr('src')) node.attr('src', field('video', 'Video · fuente', { url: assetRef(node.attr('src')), id: 0 }))

      if (node.attr('href') && el.tagName === 'a') node.attr('href', field('url', 'Destino · ' + excerpt(node.text()), { url: node.attr('href') }))

      for (const a of ['aria-label', 'placeholder', 'title']) {
        if (!node.attr(a) || el.tagName === 'video' || q(el).closest('svg').length || node.attr(a).includes('%%')) continue
        node.attr(a, field('text', 'Nombre accesible · ' + excerpt(node.attr(a)), node.attr(a)))
      }
    })

    const visit = n => {
      if (n.type === 'text') {
        const value = n.data

        if (!value.trim() || value.includes('%%')) return
        // Decorative glyphs (aria-hidden arrows, the FAQ «+») stay in the template, not in the editor.
        if (!n.parent || ['style', 'script'].includes(n.parent.tagName) || q(n.parent).closest('svg, [aria-hidden="true"]').length) return
        n.data = field(value.trim().length > 90 ? 'textarea' : 'text', textLabel(q, n, value), value)

        return
      }

      (n.children || []).forEach(visit)
    }

    q.root().contents().each((_, el) => visit(el))
    let template = styleAssets(q.html())

    // Namespace SVG ids so a duplicated widget never collides.
    q('svg [id]').each((_, el) => {
      const id = q(el).attr('id')

      template = template.replaceAll('id="' + id + '"', 'id="' + id + '-%%instance%%"').replaceAll('url(#' + id + ')', 'url(#' + id + '-%%instance%%)').replaceAll('href="#' + id + '"', 'href="#' + id + '-%%instance%%"')
    })

    return { template, fields, defaults }
  }

  const written = []

  const emit = (file, value) => {
    const target = path.join(plugin, file)

    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, value.endsWith('\n') ? value : value + '\n')
    written.push(file)
  }

  const titleFor = (q, el, i) => excerpt(q(el).find('summary,h3,h4,strong').first().text() || q(el).text()).slice(0, 40) || 'Elemento ' + (i + 1)
  const repeatLabels = o.repeatLabels || { faq: 'Preguntas' }

  /* ---------- 2. Compile each section into schema + template ---------- */

  for (const [key, title, scheme] of modules) {
    const root = $('section[data-gh-module="' + key + '"]').clone()
    const q = cheerio.load($.html(root), { decodeEntities: false }, false)
    const groups = [...new Set(q('[data-gh-repeat]').map((_, el) => q(el).attr('data-gh-repeat')).get())]
    const repeaters = []

    for (const group of groups) {
      const nodes = q('[data-gh-repeat="' + group + '"]')
      const rows = []
      const fields = new Map()
      const variants = {}
      const seen = new Map()

      nodes.each((i, node) => {
        const el = q(node).clone()

        el.removeAttr('data-gh-repeat')
        // Which row opens is a row option rendered from %%row_first%%, not a separate layout.
        el.removeAttr('open').attr('data-gh-open', '%%row_first%%')
        const compiled = compileFragment(q.html(el), key)
        let variant = seen.get(compiled.template)

        if (!variant) {
          variant = 'layout_' + seen.size
          seen.set(compiled.template, variant)
          const file = `${key}--${group}-${variant}.html`

          variants[variant] = { label: titleFor(q, node, i), templates: { item: file } }
          emit(`includes/${landing}/templates/` + file, compiled.template)
        }

        compiled.fields.forEach(f => { if (!fields.has(f.key)) fields.set(f.key, f) })
        rows.push({ _id: crypto.createHash('sha1').update(key + group + i).digest('hex').slice(0, 7), _layout: variant, ...compiled.defaults })
      })

      nodes.first().before(token('repeat_' + group))
      nodes.remove()
      if (Object.keys(variants).length === 1) Object.values(variants)[0].label = 'Estándar'
      const kinds = {}

      const rowFields = [...fields.values()].map(f => {
        const kind = f.label.split(' · ')[0]

        kinds[kind] = (kinds[kind] || 0) + 1

        return { ...f, label: kind + (kinds[kind] > 1 ? ' ' + kinds[kind] : '') }
      })

      repeaters.push({ key: group, label: repeatLabels[group] || group, parts: ['item'], fields: rowFields, variants, defaults: rows })
    }

    const compiled = compileFragment(q.html(), key)
    const extra = []
    const extraDefaults = {}
    let structuredData

    if (key === o.formModule) {
      extra.push(...FORM_FIELDS)
      Object.assign(extraDefaults, {
        form_key: process.env[envPrefix + '_FORM_KEY'] || '',
        form_surface: process.env[envPrefix + '_FORM_SURFACE'] || '',
        form_fallback: FORM_FALLBACK,
      })
    }

    if (key === o.serviceModule) {
      structuredData = { faq: o.faq, service: true }
      extra.push(...SERVICE_FIELDS)
      Object.assign(extraDefaults, o.serviceDefaults)
    }

    const definition = {
      schema: landing + 'Module.v1', module: key, title, scheme,
      fields: [...compiled.fields, ...extra], defaults: { ...compiled.defaults, ...extraDefaults },
      repeaters, ...(structuredData ? { structuredData } : {}), sourceSha256,
    }

    emit(`includes/${landing}/templates/` + key + '.html', compiled.template)
    emit(`includes/${landing}/schemas/` + key + '.json', JSON.stringify(definition, null, 2))
  }

  /* ---------- 3. Scoped stylesheet (+ optional unscoped page layer) ---------- */

  const canvasCss = source.match(/<style>([\s\S]*?)<\/style>/)[1]
  const css = styleAssets(canvasCss).replaceAll('%%asset_base%%', `../img/${landing}/`) + '\n/* Expanded selectors */\n' + tabCss.join('\n') + '\n' + fs.readFileSync(path.join(sourceDir, 'host.css'), 'utf8') + '\n' + OHIO_LINK_GUARD
  const ast = postcss.parse(css)

  ast.walkRules(rule => {
    for (let p = rule.parent; p; p = p.parent) if (p.type === 'atrule' && /keyframes/.test(p.name)) return
    rule.selectors = rule.selectors.map(s => {
      // Element selectors only: never rewrite class names that merely contain «body» or «html».
      s = s.replace(/:root|(^|[\s>+~(,])(html|body)(?=$|[\s.:#[>+~),])/g, (m, pre) => (m === ':root' ? scope : pre + scope))

      return s.startsWith(scope) ? s : scope + ' ' + s
    })
  })

  const header = `/* Generated by greenhouse-eo scripts/public-website/${o.compilerFile || `compile-${landing}-elementor-source.cjs`}. Do not edit by hand. */\n`
  const pageLayer = o.pageLayer ? '\n/* Page layer (unscoped, guarded by :has) */\n' + fs.readFileSync(path.join(sourceDir, 'page.css'), 'utf8') : ''

  emit(`assets/css/${landing}-landing.css`, header + ast.toString() + pageLayer)

  const assetPattern = new RegExp(`@${landing}\\/([\\w.-]+)|\\.\\.\\/img\\/${landing}\\/([\\w.-]+)|%%asset_base%%([\\w.-]+)`, 'g')
  const usedAssets = [...new Set(written.flatMap(f => [...fs.readFileSync(path.join(plugin, f), 'utf8').matchAll(assetPattern)].map(m => m[1] || m[2] || m[3])))]

  fs.writeFileSync(path.join(sourceDir, 'used-assets.json'), JSON.stringify(usedAssets.sort(), null, 2) + '\n')

  return { files: written.length, modules: modules.length, assets: usedAssets.length, sourceSha256 }
}

module.exports = { compileSourceLedLanding }
